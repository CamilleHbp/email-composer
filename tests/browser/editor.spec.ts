test('recover an unsaved draft and export an uploaded image as a CID attachment', async ({ page }) => {
  await page.goto('/');
  await page.getByLabel('Email address').fill('test@example.test');
  await page.getByLabel('Password', { exact: true }).fill('test-password-12345');
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await page.getByRole('button', { name: 'Create an email', exact: true }).click();
  await expect(page.getByLabel('Name', { exact: true })).toHaveValue('Untitled email');
  await page.route('**/api/templates/*', route => route.request().method() === 'PUT' ? route.abort() : route.continue());
  await page.getByLabel('Name', { exact: true }).fill('Recovered image letter');
  await expect(page.getByRole('status')).toContainText('Save failed', { timeout: 10000 });
  await page.reload();
  await page.unroute('**/api/templates/*');
  await page.getByRole('button', { name: 'Open Untitled email', exact: true }).click();
  await page.getByRole('button', { name: 'Restore copy', exact: true }).click();
  await expect(page.getByLabel('Name', { exact: true })).toHaveValue('Recovered image letter');
  await expect(page.getByRole('status')).toContainText('All changes saved', { timeout: 10000 });
  await page.getByRole('button', { name: 'Image', exact: true }).click();
  await page.getByRole('button', { name: 'Choose an image', exact: true }).last().click();
  const png = await sharp({ create: { width: 20, height: 20, channels: 3, background: '#26735b' } }).png().toBuffer();
  await page.locator('dialog input[type=file]').setInputFiles({ name: 'green.png', mimeType: 'image/png', buffer: png });
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.getByLabel('Image description', { exact: true }).fill('A green square');
  await expect(page.getByRole('status')).toContainText('All changes saved', { timeout: 10000 });
  await page.getByRole('button', { name: 'Use this email', exact: true }).click();
  await page.getByText('Other formats', { exact: true }).click();
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Download embedded email', exact: true }).click();
  const stream = await (await downloadPromise).createReadStream();
  const parsed = await simpleParser(stream!, { skipImageLinks: true });
  expect(parsed.attachments).toHaveLength(1);
  expect(parsed.attachments[0].contentType).toBe('image/png');
  expect(parsed.attachments[0].contentId).toBeTruthy();
  expect(parsed.html).toContain(`cid:${parsed.attachments[0].contentId!.replace(/^<|>$/g, '')}`);
  expect(parsed.attachments[0].related).toBe(true);
});

test('recover a stale local copy without overwriting a newer server revision', async ({ page }) => {
  await page.goto('/');
  await page.getByLabel('Email address').fill('test@example.test');
  await page.getByLabel('Password', { exact: true }).fill('test-password-12345');
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  const creation = page.waitForResponse(r => r.url().endsWith('/api/templates') && r.request().method() === 'POST');
  await page.getByRole('button', { name: 'Create an email', exact: true }).click();
  const record = await (await creation).json();
  await page.route('**/api/templates/*', route => route.request().method() === 'PUT' ? route.abort() : route.continue());
  await page.getByLabel('Name', { exact: true }).fill('Local work worth keeping');
  await expect(page.getByRole('status')).toContainText('Save failed', { timeout: 10000 });
  const response = await page.request.put(`/api/templates/${record.id}`, {
    data: { ...record, name: 'Newer server work' }, headers: { Origin: 'http://localhost:5173' },
  });
  expect(response.ok()).toBe(true);
  await page.reload();
  await page.unroute('**/api/templates/*');
  await page.getByRole('button', { name: 'Open Newer server work', exact: true }).click();
  await page.getByRole('button', { name: 'Restore copy', exact: true }).click();
  await expect(page.getByLabel('Name', { exact: true })).toHaveValue('Local work worth keeping');
  await expect(page.getByRole('status')).toContainText('This design changed in another tab');
  await page.getByRole('button', { name: 'Save a separate copy', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Open Local work worth keeping', exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Open Newer server work', exact: true })).toBeVisible();
});


test('preview matches the rich HTML copied for pasting into a mail composer', async ({ page, context }) => {
  await context.grantPermissions(['clipboard-read', 'clipboard-write']);
  await page.goto('/');
  await page.getByLabel('Email address').fill('test@example.test');
  await page.getByLabel('Password', { exact: true }).fill('test-password-12345');
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await page.getByRole('button', { name: 'Create an email', exact: true }).click();
  await page.getByRole('button', { name: 'Text', exact: true }).click();
  await page.getByRole('textbox', { name: 'Content', exact: true }).fill('A message to paste');
  await page.getByRole('button', { name: 'Preview', exact: true }).click();
  await expect(page.getByText('Copy/paste preview', { exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Full email', exact: true })).toHaveCount(0);
  const preview = await page.frameLocator('iframe').locator('body').innerHTML();
  await page.getByRole('button', { name: 'Copy formatted email', exact: true }).click();
  await expect(page.getByText('Email copied. Paste it into your mail app.', { exact: true })).toBeVisible();
  const copied = await page.evaluate(async () => {
    const [item] = await navigator.clipboard.read();
    const html = await (await item.getType('text/html')).text();
    const parsed = new DOMParser().parseFromString(html, 'text/html');
    // Chromium can attach a charset declaration when reading clipboard HTML.
    parsed.querySelectorAll('meta').forEach(el => el.remove());
    return { html: parsed.body.innerHTML, text: await (await item.getType('text/plain')).text() };
  });
  expect(copied.html).toBe(preview);
  expect(copied.text).toContain('A message to paste');
});
