test('drag preview matches nested insertion and clears after drop or cancellation', async ({ page }) => {
  await page.goto('/');
  await page.getByLabel('Email address').fill('test@example.test');
  await page.getByLabel('Password', { exact: true }).fill('test-password-12345');
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await page.getByRole('button', { name: 'Create an email', exact: true }).click();
  await page.getByRole('button', { name: 'Section', exact: true }).click();
  await page.getByRole('button', { name: 'Text', exact: true }).click();
  const target = page.locator('.kind-section .kind-text').last();
  const targetId = await target.getAttribute('data-node-id');
  const rect = (await target.boundingBox())!;
  const source = page.locator('.block-grid').getByRole('button', { name: 'Heading', exact: true });
  const dataTransfer = await page.evaluateHandle(() => new DataTransfer());
  await source.dispatchEvent('dragstart', { dataTransfer });
  await target.dispatchEvent('dragover', { dataTransfer, clientX: rect.x + 30, clientY: rect.y + 2 });
  const indicator = page.locator('.drop-indicator');
  await expect(indicator).toBeVisible();
  const marker = (await indicator.boundingBox())!;
  expect(Math.abs(marker.y - rect.y)).toBeLessThan(10);
  await target.dispatchEvent('drop', { dataTransfer, clientX: rect.x + 30, clientY: rect.y + 2 });
  await expect(indicator).toHaveCount(0);
  const inserted = page.locator(`[data-node-id="${targetId}"]`).locator('..').locator('xpath=preceding-sibling::*[1]').locator('.kind-heading');
  await expect(inserted).toHaveCount(1);
  const insertedId = await inserted.getAttribute('data-node-id');
  await inserted.click();
  const handle = inserted.locator(':scope > .node-handle');
  await handle.dispatchEvent('dragstart', { dataTransfer });
  const updatedRect = (await target.boundingBox())!;
  await target.dispatchEvent('dragover', { dataTransfer, clientX: updatedRect.x + 30, clientY: updatedRect.y + updatedRect.height - 2 });
  await expect(indicator).toBeVisible();
  await target.dispatchEvent('drop', { dataTransfer, clientX: updatedRect.x + 30, clientY: updatedRect.y + updatedRect.height - 2 });
  await expect(indicator).toHaveCount(0);
  await expect(target.locator('..').locator('xpath=following-sibling::*[1]').locator('.kind-heading')).toHaveAttribute('data-node-id', insertedId!);
  await source.dispatchEvent('dragstart', { dataTransfer });
  await target.dispatchEvent('dragover', { dataTransfer, clientX: rect.x + 30, clientY: rect.y + 2 });
  await expect(indicator).toBeVisible();
  await source.dispatchEvent('dragend', { dataTransfer });
  await expect(indicator).toHaveCount(0);
});

test('inside drop preview stays within empty and populated containers without padding', async ({ page }) => {
  await page.goto('/');
  await page.getByLabel('Email address').fill('test@example.test');
  await page.getByLabel('Password', { exact: true }).fill('test-password-12345');
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await page.getByRole('button', { name: 'Create an email', exact: true }).click();
  await page.getByRole('button', { name: 'Section', exact: true }).click();
  const section = page.locator('.kind-section').last();
  await page.getByRole('spinbutton', { name: /^Padding/ }).fill('0');
  const source = page.locator('.block-grid').getByRole('button', { name: 'Heading', exact: true });
  const indicator = page.locator('.drop-indicator');
  for (const populated of [false, true]) {
    const dataTransfer = await page.evaluateHandle(() => new DataTransfer());
    await source.dispatchEvent('dragstart', { dataTransfer });
    const rect = (await section.boundingBox())!;
    const point = { dataTransfer, clientX: rect.x + 5, clientY: rect.y + rect.height / 2 };
    await section.dispatchEvent('dragover', point);
    await expect(indicator).toBeVisible();
    await expect(section).toHaveClass(/drop-container/);
    await expect(indicator).toHaveAttribute('data-drop-parent', (await section.getAttribute('data-node-id'))!);
    const line = (await indicator.boundingBox())!;
    expect(line.x).toBeGreaterThan(rect.x);
    expect(line.x + line.width).toBeLessThan(rect.x + rect.width);
    expect(line.y).toBeGreaterThan(rect.y);
    expect(line.y + line.height).toBeLessThan(rect.y + rect.height);
    if (!populated) expect(Math.abs(line.y - (rect.y + rect.height / 2))).toBeLessThan(2);
    await section.dispatchEvent('drop', point);
    await expect(section.locator('.kind-heading')).toHaveCount(populated ? 2 : 1);
    await expect(indicator).toHaveCount(0);
    await expect(section).not.toHaveClass(/drop-container/);
  }
  await page.locator('.document-settings').click();
  await page.getByRole('button', { name: 'Columns', exact: true }).click();
  const column = page.locator('.kind-column').last();
  const rect = (await column.boundingBox())!;
  const dataTransfer = await page.evaluateHandle(() => new DataTransfer());
  await source.dispatchEvent('dragstart', { dataTransfer });
  const point = { dataTransfer, clientX: rect.x + rect.width / 2, clientY: rect.y + rect.height / 2 };
  await column.locator('.empty-container').dispatchEvent('dragover', point);
  await expect(column).toHaveClass(/drop-container/);
  const line = (await indicator.boundingBox())!;
  expect(line.x).toBeGreaterThan(rect.x);
  expect(line.x + line.width).toBeLessThan(rect.x + rect.width);
  expect(Math.abs(line.y - (rect.y + rect.height / 2))).toBeLessThan(2);
  await column.locator('.empty-container').dispatchEvent('drop', point);
  await expect(column.locator('.kind-heading')).toHaveCount(1);
  await expect(indicator).toHaveCount(0);
});

