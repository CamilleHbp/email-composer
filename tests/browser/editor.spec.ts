test('preview matches the rich HTML copied for pasting into a mail composer', async ({ page, context }) => {
  await context.grantPermissions(['clipboard-read', 'clipboard-write']);
  await page.goto('/');
  await page.getByLabel('Email address').fill('test@example.test');
  await page.getByLabel('Password', { exact: true }).fill('test-password-12345');
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await page.getByRole('button', { name: 'Create an email', exact: true }).click();
  await page.getByRole('button', { name: 'Text', exact: true }).click();
  await page.getByRole('textbox', { name: 'Content', exact: true }).fill('A message to paste');
  await page.getByRole('button', { name: 'Preview', exact: true }).click();
  await expect(page.getByText('Copy/paste preview', { exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Full email', exact: true })).toHaveCount(0);
  const preview = await page.frameLocator('iframe').locator('body').innerHTML();
  await page.getByRole('button', { name: 'Copy formatted email', exact: true }).click();
  await expect(page.getByText('Email copied. Paste it into your mail app.', { exact: true })).toBeVisible();
  const copied = await page.evaluate(async () => {
    const [item] = await navigator.clipboard.read();
    const html = await (await item.getType('text/html')).text();
    const parsed = new DOMParser().parseFromString(html, 'text/html');
    // Chromium can attach a charset declaration when reading clipboard HTML.
    parsed.querySelectorAll('meta').forEach(el => el.remove());
    return { html: parsed.body.innerHTML, text: await (await item.getType('text/plain')).text() };
  });
  expect(copied.html).toBe(preview);
  expect(copied.text).toContain('A message to paste');
});

